"""Research-only components for a proof-carrying causal investment system.

No investment recommendation or market orders are generated by this module.
This code is a testable prototype, not a statistically validated trading system.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
from math import log
from typing import Iterable


def _aware(dt: datetime) -> bool:
    return dt.tzinfo is not None and dt.utcoffset() is not None


@dataclass(frozen=True)
class Evidence:
    event_id: str
    source_url: str
    document_sha256: str
    published_at: datetime
    first_observed_at: datetime
    available_at: datetime
    statement: str

    def verify_as_of(self, as_of: datetime) -> None:
        for dt in (self.published_at, self.first_observed_at, self.available_at, as_of):
            if not _aware(dt):
                raise ValueError('All timestamps must be timezone-aware')
        if not self.source_url.startswith('https://'):
            raise ValueError('Primary/source document URL over TLS required (v0.2)')
        if len(self.document_sha256) != 64 or any(c not in '0123456789abcdef' for c in self.document_sha256):
            raise ValueError('Valid SHA-256 digest required')
        # The economically usable timestamp cannot precede public disclosure or receipt.
        if self.available_at < max(self.published_at, self.first_observed_at):
            raise ValueError('available_at cannot precede publication or observation')
        if self.available_at > as_of:
            raise ValueError('LOOKAHEAD BIAS: evidence not available at forecast time')


def evidence_digest(content: bytes) -> str:
    """Digest of the ARCHIVED bytes. v0.1 accepted any 64-hex string; v0.2 callers
    must derive document_sha256 from the stored snapshot via this helper."""
    import hashlib
    return hashlib.sha256(content).hexdigest()


@dataclass(frozen=True)
class BinaryThesis:
    hypothesis_id: str
    success_horizon: datetime
    success_definition: str
    p_success_low: float
    p_success_high: float
    upside_multiple: float
    downside_multiple: float
    evidence_ids: tuple[str, ...]
    forecaster_version: str

    def validate(self, forecast_at: datetime) -> None:
        if not _aware(self.success_horizon) or not _aware(forecast_at):
            raise ValueError('Date fields must be timezone-aware')
        if self.success_horizon <= forecast_at:
            raise ValueError('Outcome horizon must follow forecast')
        if not (0 <= self.p_success_low <= self.p_success_high <= 1):
            raise ValueError('Incoherent probability interval')
        if not (0 <= self.downside_multiple < 1 < self.upside_multiple):
            raise ValueError('Prototype requires 0<=downside<1<upside')
        if not self.evidence_ids or not self.success_definition:
            raise ValueError('Auditable evidence and a falsifiable outcome required')


@dataclass(frozen=True)
class AllocationCertificate:
    hypothesis_id: str
    max_portfolio_fraction: float
    lower_bound_success_probability: float
    robust_log_growth_before_fixed_costs: float
    expected_multiple_at_lower_bound: float
    success_definition: str
    evidence_ids: tuple[str, ...]
    risk_valid: bool
    interpretation: str


def growth(w: float, p: float, up: float, down: float) -> float:
    """Two-state expected log-wealth change with wealth-multiples up/down.

    All distributional assumptions are unverified until separately calibrated.
    """
    if not (0 <= w <= 1 and 0 <= p <= 1 and up > 1 and 0 <= down < 1):
        raise ValueError('Bad two-state assumptions')
    success = 1 + w * (up - 1)
    failure = 1 + w * (down - 1)
    if min(success, failure) <= 0:
        raise ValueError('Bankrupt-state log undefined')
    return p * log(success) + (1-p) * log(failure)


def robust_binary_allocation(thesis: BinaryThesis, *, forecast_at: datetime,
                             max_fraction: float = .05, fixed_cost_fraction_of_portfolio: float = 0) -> AllocationCertificate:
    """Max-min log utility for a *hypothetical* two-outcome model.

    Worst case is the lower probability bound because the up multiple exceeds down.
    Not a proof that the probability interval covers the real-world probability.
    """
    thesis.validate(forecast_at)
    if not (0 <= max_fraction < 1):
        raise ValueError('max_fraction must be in [0,1)')
    if not (0 <= fixed_cost_fraction_of_portfolio < 1):
        raise ValueError('cost fraction must be in [0,1)')
    p = thesis.p_success_low
    a = thesis.upside_multiple - 1
    b = thesis.downside_multiple - 1
    # FOC for p log(1+a*w)+(1-p)log(1+b*w):
    # w* = -(p*a + (1-p)*b) / (a*b)
    w_opt = -(p * a + (1-p) * b) / (a * b)
    w = max(0.0, min(max_fraction, w_opt))
    lower_growth = growth(w, p, thesis.upside_multiple, thesis.downside_multiple)
    # v0.2: compare log-growth with the log-cost of paying a fraction c of wealth,
    # -log(1-c), not with c itself (unit mismatch in v0.1; equal only to first order).
    log_cost = -log(1 - fixed_cost_fraction_of_portfolio)
    if lower_growth <= log_cost:
        w = 0.0
        lower_growth = 0.0
    return AllocationCertificate(
        hypothesis_id=thesis.hypothesis_id,
        max_portfolio_fraction=w,
        lower_bound_success_probability=p,
        robust_log_growth_before_fixed_costs=lower_growth,
        expected_multiple_at_lower_bound=(p*thesis.upside_multiple + (1-p)*thesis.downside_multiple),
        success_definition=thesis.success_definition,
        evidence_ids=thesis.evidence_ids,
        risk_valid=(0 <= w <= max_fraction),
        interpretation='CONDITIONAL: assuming two-state payoffs and a valid p interval; not a real-world profit guarantee.'
    )


def coherent_binary_probs(p_yes: float, p_no: float, tolerance: float = 1e-8) -> bool:
    return (0 <= p_yes <= 1 and 0 <= p_no <= 1 and
            abs(p_yes+p_no-1) <= tolerance)


class ChallengerEvidence:
    """DEPRECATED in v0.2: use cpe.eprocess.CommittedEProcess.

    This class accepts forecast probabilities at resolution time, has no event
    identity and allows betting_fraction == 1. Kept for backward compatibility of
    the v0.1 tests only; it emits a DeprecationWarning.

    An anytime-valid e-process for sequential *pre-registered* Brier score comparisons.

    Under H0, if E[loss_baseline - loss_challenger | past] <= 0,
    product(1 + lam_t*(loss_baseline-loss_challenger)) is a test supermartingale.
    The statement requires properly resolved pre-registered forecasts and null assumptions.
    """
    def __init__(self, betting_fraction: float = 0.5) -> None:
        import warnings
        warnings.warn('ChallengerEvidence is deprecated; use cpe.eprocess.CommittedEProcess', DeprecationWarning, stacklevel=2)
        if not 0 <= betting_fraction < 1:
            raise ValueError('betting_fraction in [0,1); 1 creates an absorbing zero')
        self.betting_fraction = betting_fraction
        self.evalue = 1.0
        self.n = 0

    def update(self, baseline_probability: float, challenger_probability: float, outcome: int) -> float:
        if outcome not in (0, 1):
            raise ValueError('Outcome must be binary')
        if not (0 <= baseline_probability <= 1 and 0 <= challenger_probability <= 1):
            raise ValueError('Probabilities must be valid')
        loss_baseline = (baseline_probability-outcome)**2
        loss_challenger = (challenger_probability-outcome)**2
        improvement = loss_baseline-loss_challenger  # bounded [-1,1]
        self.evalue *= 1 + self.betting_fraction * improvement
        self.n += 1
        return self.evalue

    def reject_null(self, alpha: float = .05) -> bool:
        if not 0 < alpha < 1:
            raise ValueError('alpha invalid')
        return self.evalue >= 1/alpha
