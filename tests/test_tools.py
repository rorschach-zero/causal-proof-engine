def _git(repo: Path, *args: str, env: dict[str, str] | None = None) -> str:
    base_env = {"GIT_AUTHOR_NAME": "Salah Aouaj", "GIT_AUTHOR_EMAIL": "salah@hydeout.ch",
                "GIT_COMMITTER_NAME": "Salah Aouaj", "GIT_COMMITTER_EMAIL": "salah@hydeout.ch", "HOME": str(repo)}
    if env:
        base_env.update(env)
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True,
                          env={**base_env, "PATH": "/usr/bin:/bin"}).stdout.strip()


