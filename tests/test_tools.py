def test_t09_identity_is_checked_on_metadata_not_text() -> None:
    assert identity_findings(commit("clean message")) == []
    tool = commit("clean message", author="Claude <noreply@anthropic.com>")
    assert len(identity_findings(tool)) == 1
    both = commit("clean message", author="Someone <s@example.org>", committer="GitHub <noreply@github.com>")
    assert len(identity_findings(both)) == 2


MATRIX_DOC = "# 16\n\n**Version:** v51, 2026-10-19. **Round:** 50 (round 50: ...)\n"
SPEC_DOC = "# 17\n\nStatus: **PROPOSED**,\nversion 47 (round 50: applies ...)\n"


def test_rc277_merge_message_must_name_the_tree_labels() -> None:
    labels = tree_labels_from_texts(MATRIX_DOC, SPEC_DOC)
    assert labels == TreeLabels(51, 50, 47, 50)
    stale = "Reconciliation rounds 1–49: matrix v50 and amended Phase 1 specification v46"
    current = "Reconciliation rounds 1–50: matrix v51 and amended Phase 1 specification v47"
    assert len(label_findings(stale, labels, "msg")) == 3
    assert label_findings(current, labels, "msg") == []
    assert label_findings("Add CI", labels, "msg") == []
    assert label_findings("matrix v51", TreeLabels(None, None, None, None), "msg") != []


def _git(repo: Path, *args: str, env: dict[str, str] | None = None) -> str:
    base_env = {"GIT_AUTHOR_NAME": "Salah Aouaj", "GIT_AUTHOR_EMAIL": "salah@hydeout.ch",
                "GIT_COMMITTER_NAME": "Salah Aouaj", "GIT_COMMITTER_EMAIL": "salah@hydeout.ch", "HOME": str(repo)}
    if env:
        base_env.update(env)
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True,
                          env={**base_env, "PATH": "/usr/bin:/bin"}).stdout.strip()


