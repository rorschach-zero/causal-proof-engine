def test_rc279_single_parent_squash_with_a_stale_message_fails_and_a_current_one_passes(repo: Path) -> None:
    base = _git(repo, "rev-parse", "HEAD")
    (repo / "note.txt").write_text("x")
    _git(repo, "add", ".")
    _git(repo, "commit", "-q", "-m", "Reconciliation rounds 1–49: matrix v50 and amended Phase 1 specification v46")
    findings = check_provenance.check(f"{base}..HEAD", repo, None, None, "HEAD")
    assert len(findings) == 3 and all("names" in f for f in findings)
    (repo / "note.txt").write_text("y")
    _git(repo, "commit", "-q", "-am", "Reconciliation rounds 1–50: matrix v51 and amended Phase 1 specification v47")
    head = _git(repo, "rev-parse", "HEAD")
    assert check_provenance.check(f"{head}~1..{head}", repo, None, None, "HEAD") == []


def test_prospective_pr_text_is_checked_against_the_head_tree_and_identity_on_metadata(repo: Path) -> None:
    base = _git(repo, "rev-parse", "HEAD")
    (repo / "note.txt").write_text("x")
    _git(repo, "add", ".")
