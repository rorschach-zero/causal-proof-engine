def test_provenance_cli_reports_and_exits_nonzero_on_findings(repo: Path, capsys: pytest.CaptureFixture[str]) -> None:
    base = _git(repo, "rev-parse", "HEAD")
    (repo / "note.txt").write_text("x")
    _git(repo, "add", ".")
    _git(repo, "commit", "-q", "-m", "Add note\n\nCo-Authored-By: Codex <codex@openai.com>")
    assert check_provenance.main(["--range", f"{base}..HEAD", "--repo", str(repo)]) == 1
    assert "attribution trailer" in capsys.readouterr().out
    _git(repo, "commit", "-q", "--amend", "-m", "Add note")
    assert check_provenance.main(["--range", f"{base}..HEAD", "--repo", str(repo)]) == 0


def test_import_boundary_flags_network_executor_and_evidence_imports(tmp_path: Path) -> None:
    package = tmp_path / "cpe"
    (package / "executor").mkdir(parents=True)
    (package / "__init__.py").write_text("")
    (package / "clean.py").write_text("import json\nfrom cpe.ledger import Ledger\n")
    (package / "leaky.py").write_text("import urllib.request\nfrom http import client\n")
    (package / "research.py").write_text("from cpe.executor import place_order\nimport research.reproduction.round2_checks\n")
    (package / "executor" / "__init__.py").write_text("from cpe.executor.core import x\n")
    findings = check_import_boundary.check_package(package)
    assert len([f for f in findings if "leaky.py" in f]) == 2
    assert len([f for f in findings if "research.py" in f and "executor" in f]) == 1
    assert len([f for f in findings if "evidence scripts" in f]) == 1
    assert not any("clean.py" in f or "executor/__init__.py" in f for f in findings)


